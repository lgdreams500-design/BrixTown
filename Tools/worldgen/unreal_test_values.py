"""Writes the values the Unreal build's tests check its ports against (TECH-004: rules proved here first, then built in
the engine):
- which stone, brick or paving pattern every lot and block uses, and in what colour (world.surfaces(), ADR-0017, WLD-038,
  WLD-039), read by BrixTown.World.WLD038_surfaces_match_the_rules;
- where the sun is in each season at the hours of a day (world.sun_heights(), world.sun_place(), ADR-0024, WLD-043), read
  by BrixTown.World.WLD043_the_sun_follows_the_calendar;
- where some residents are at some minutes of the built day (citysim City.at()), read by
  BrixTown.World.CITY022_residents_are_where_their_routine_puts_them;
- where some vehicles are at some minutes of that day (citysim traffic car_at()), read by
  BrixTown.World.CITY040_vehicles_are_where_the_traffic_puts_them;
- when repair crews mend a list of crash damage (citysim repairs.repairs(), CITY-075), read by
  BrixTown.World.CITY075_repair_crews_mend_as_repairs_py_does (python unreal_test_values.py repairs: only that, quickly);
- the weather through a day: its light numbers and how wet the paving is (world.weather_now(), WLD-037), read by
  BrixTown.World.WLD037_the_weather_is_worked_out_as_world_py_does (python unreal_test_values.py weather).
The tests are in Game/Source/BrixWorld.

Run after changing World/ (and build_play.py, which writes the day these values are checked against):
    cd Tools/worldgen
    python unreal_test_values.py
"""
import json
import math
import os
import sys

import world

HERE = os.path.dirname(os.path.abspath(__file__))
VALUES = os.path.normpath(os.path.join(HERE, "..", "..", "Tests", "values"))
OUT = os.path.join(VALUES, "surfaces_city_01.json")
SUN = os.path.join(VALUES, "sun_city_01.json")
RESIDENTS = os.path.join(VALUES, "residents_city_01.json")
CARS = os.path.join(VALUES, "cars_city_01.json")
REPAIRS = os.path.join(VALUES, "repairs_city_01.json")
WEATHER = os.path.join(VALUES, "weather_city_01.json")
DAY = 16                                                # the day build_play.py builds for the slice and for Unreal (Game/Data/day.json)
MINUTES = (0, 300, 440, 600, 780, 1020, 1200, 1380)    # a night, a dawn, the slice's start (07:20), midday, an evening


def main():
    W = world.load()
    S = world.surfaces(W)
    names = S["patterns"]
    lots = {}
    for lid, v in sorted(S["lots"].items()):
        if "wall" in v:
            lots[lid] = dict(wall=names[v["wall"]], color=v["color"], upper=v["upper"])
        else:
            lots[lid] = dict(ground=names[v["ground"]], color=v["color"])
    blocks = {bid: dict(pavement=names[v["pavement"]], color=v["color"]) for bid, v in sorted(S["blocks"].items())}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(dict(note="Generated by Tools/worldgen/unreal_test_values.py from world.surfaces(); do not edit.",
                       lots=lots, blocks=blocks), f, indent=1, sort_keys=True)
        f.write("\n")
    print("wrote %s: %d lots, %d blocks" % (OUT, len(lots), len(blocks)))

    # the sun: each season's declination, and its direction (east +x, up +y, south +z) at the hours of a day, the hour angle
    # being 0 at the middle of the calendar's day (play.js sunHour())
    cal = W["calendar"]["calendar"]
    days = len(cal["seasons"]) * cal["days_per_season"]
    seasons = {}
    for k, name in enumerate(cal["seasons"]):
        noon = (cal["sunrise"][k] + cal["sunset"][k]) * 30
        seasons[name] = dict(declination=world.sun_heights(W)[name], places={
            str(m): [round(v, 9) for v in world.sun_place(W, name, (m - noon) / 1440 * 2 * math.pi)] for m in MINUTES})
    sun = dict(note="Generated by Tools/worldgen/unreal_test_values.py from world.sun_heights() and world.sun_place(); do not edit.",
               season_of_day={str(d): cal["seasons"][(d % days) // cal["days_per_season"]] for d in (0, 11, 12, 16, 30, 47, 48, 100)},
               seasons=seasons)
    with open(SUN, "w", encoding="utf-8", newline="\n") as f:
        json.dump(sun, f, indent=1, sort_keys=True)
        f.write("\n")
    print("wrote %s: %d seasons" % (SUN, len(seasons)))

    # where residents are (citysim City.at(), the truth the slice's resident() and the Unreal port follow; CITY-022): every
    # 50th resident at eight minutes of the slice's day, as a position (x, z) and a state; no position when away or in a vehicle
    city = world.simulation(W, traffic=True)
    city.plan(DAY)
    ids = [r["id"] for r in W["residents"]][::50]
    at = {}
    for m in (300, 450, 480, 520, 720, 1000, 1080, 1260):
        now = city.at(DAY * 1440 + m)
        at[str(m)] = {rid: dict(state=now[rid]["state"], pos=[round(c, 4) for c in now[rid]["pos"]] if now[rid]["pos"] is not None and now[rid]["state"] not in ("driving", "riding") else None) for rid in ids}
    with open(RESIDENTS, "w", encoding="utf-8", newline="\n") as f:
        json.dump(dict(note="Generated by Tools/worldgen/unreal_test_values.py from citysim City.at() for day %d; do not edit." % DAY, day=DAY, at=at), f, indent=1, sort_keys=True)
        f.write("\n")
    print("wrote %s: %d residents at %d minutes" % (RESIDENTS, len(ids), len(at)))

    # where vehicles are (traffic.car_at(), the truth the slice's Cars.at() and the Unreal port follow; CITY-040): every
    # 7th vehicle of the day in Game/Data/cars.json's order at minutes through the day, a position and heading, or none
    T = city.traffic
    cids = T.ids(DAY)
    picked = list(range(0, len(cids), 7))
    cars = {}
    for m in (330, 455, 481.3, 522.7, 725, 1003.4, 1081.9, 1262):
        row = {}
        for n in picked:
            c = T.car_at(cids[n], DAY, m)
            row[str(n)] = dict(state=c["state"], pos=[round(v, 4) for v in c["pos"]] if c["pos"] is not None else None,
                               heading=[round(v, 4) for v in c["heading"]] if c.get("heading") is not None else None)
        cars[str(m)] = row
    with open(CARS, "w", encoding="utf-8", newline="\n") as f:
        json.dump(dict(note="Generated by Tools/worldgen/unreal_test_values.py from citysim traffic car_at() for day %d; do not edit." % DAY,
                       day=DAY, ids=[cids[n] for n in picked], at=cars), f, indent=1, sort_keys=True)
        f.write("\n")
    print("wrote %s: %d vehicles at %d minutes" % (CARS, len(picked), len(cars)))


def repairs_values():
    """CITY-075: forty pieces of damage across the town over two days, at night and by day, some at the same minute, and
    when the crews from the town's depots mend each (repairs.py, the rule smash.js and the Unreal build follow)."""
    sys.path.insert(0, os.path.join(HERE, "..", "citysim"))
    import repairs
    w = world.load()
    L = world.lots(w)
    depots = sorted((l["id"], tuple(l["door"])) for l in L if l["kind"] == "utility" and l.get("enterable"))
    kinds = sorted(w["crash"]["kinds"])
    damage = []
    for i in range(40):
        l = L[(i * 37) % len(L)]
        x0, z0, x1, z1 = l["rect"]
        at = DAY * 1440 + 300 + (i // 2) * 47.3                 # two at each minute: ties go by id
        damage.append(dict(id="%s@%d" % (kinds[i % len(kinds)], i), kind=kinds[i % len(kinds)], at=round(at, 3), pos=(x0, z0) if i % 3 else ((x0 + x1) / 2, (z0 + z1) / 2)))
    pace = w["calendar"]["calendar"]["real_seconds_per_minute"]
    plan = repairs.repairs(damage, depots, w["crash"], pace)
    with open(REPAIRS, "w", encoding="utf-8", newline="\n") as f:
        json.dump(dict(note="Generated by Tools/worldgen/unreal_test_values.py from citysim repairs.repairs(); do not edit.", pace=pace,
                       depots=[[d, list(p)] for d, p in depots], damage=[dict(d, pos=list(d["pos"])) for d in damage],
                       plan={k: dict(crew=v["crew"], leave=v["leave"], arrive=v["arrive"], done=v["done"]) for k, v in plan.items()}), f, indent=1, sort_keys=True)
        f.write("\n")
    print("wrote %s: %d pieces of damage, %d depots" % (REPAIRS, len(damage), len(depots)))


def weather_values():
    """WLD-037: world.weather_now() through days of every kind of weather, and a dry day tried as rain."""
    w = world.load()
    days = [["clear", "rain", "cloud", "fog"], ["rain", "rain", "clear", "cloud"], ["fog", "clear", "rain", "rain"], ["cloud", "clear", "clear", "clear"]]
    cases = []
    for d in days:
        for m in [k * 7.3 for k in range(198)]:
            cases.append(dict(day=d, m=round(m, 2), trying=None, want=world.weather_now(w, d, round(m, 2))))
    for m in (0, 300, 700, 1300):
        cases.append(dict(day=days[3], m=m, trying="rain", want=world.weather_now(w, days[3], m, "rain")))
    clouds = [dict(day=d, n=16 + k, m=round(m, 2), want=world.clouds_now(w, d, 16 + k, round(m, 2))) for k, d in enumerate(days) for m in [j * 11.7 for j in range(124)]]
    with open(WEATHER, "w", encoding="utf-8", newline="\n") as f:
        json.dump(dict(note="Generated by Tools/worldgen/unreal_test_values.py from world.weather_now() and world.clouds_now(); do not edit.", cases=cases, clouds=clouds), f, separators=(",", ":"))
        f.write("\n")
    print("wrote %s: %d moments" % (WEATHER, len(cases)))


if __name__ == "__main__":
    if sys.argv[1:] == ["repairs"]:
        repairs_values()
    elif sys.argv[1:] == ["weather"]:
        weather_values()
    else:
        main()
        repairs_values()
        weather_values()
