"""Writes the values the Unreal build's tests check its ports against (TECH-004: rules proved here first, then built in
the engine). Today: which stone, brick or paving pattern every lot and block uses, and in what colour (world.surfaces(),
ADR-0017, WLD-038, WLD-039), read by BrixTown.World.WLD038_surfaces_match_the_rules (Game/Source/BrixWorld).

Run after changing World/rules/surfaces.json or a block's 'surface' field:
    cd Tools/worldgen
    python unreal_test_values.py
"""
import json
import os

import world

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "Tests", "values", "surfaces_city_01.json"))


def main():
    W = world.load()
    S = world.surfaces(W)
    names = S["patterns"]
    lots = {}
    for lid, v in sorted(S["lots"].items()):
        if "wall" in v:
            lots[lid] = dict(wall=names[v["wall"]], color=v["color"], upper=v["upper"])
        else:
            lots[lid] = dict(ground=names[v["ground"]], color=v["color"])
    blocks = {bid: dict(pavement=names[v["pavement"]], color=v["color"]) for bid, v in sorted(S["blocks"].items())}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(dict(note="Generated by Tools/worldgen/unreal_test_values.py from world.surfaces(); do not edit.",
                       lots=lots, blocks=blocks), f, indent=1, sort_keys=True)
        f.write("\n")
    print("wrote %s: %d lots, %d blocks" % (OUT, len(lots), len(blocks)))


if __name__ == "__main__":
    main()
