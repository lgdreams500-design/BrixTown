"""Turns the approved writing into quest data the game runs (QST-010 to QST-015, ADR-0056).

The writing lives in docs/narrative/src, one file per quest line, in the form the Quest Atlas page shows the owner.
World/rules/story_cast.json says which resident plays each person and where the scenes are. compile() joins the two
into the form quests.py runs; `python story.py` writes it to World/rules/quests_story.json, and a test fails when that
file is not what the writing gives. So the words are written once, in the place the owner reads them.

    python story.py            write World/rules/quests_story.json
    python story.py --check    say whether it is up to date; write nothing

Standard library only.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
WRITING = os.path.join(ROOT, "docs", "narrative", "src")
CAST = os.path.join(ROOT, "World", "rules", "story_cast.json")
OUT = os.path.join(ROOT, "World", "rules", "quests_story.json")
NOTE = ("Generated by Tools/citysim/story.py from the approved writing in docs/narrative/src and World/rules/story_cast.json. "
        "Do not edit: change those and run it again. The story lines of a career (QST-010 to QST-015, ADR-0056), in the form "
        "World/rules/quests.json describes, which they are joined to when the world is loaded.")


def _read(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def compile(writing=WRITING, cast_file=CAST):
    """The story lines as quests.py runs them: {note, exclusive, quests}."""
    C = _read(cast_file)
    cast = C["cast"]
    world = _read(os.path.join(writing, "world.json"))

    def who(name):
        if name not in cast:
            raise ValueError("story_cast.json casts nobody as %s" % name)
        return cast[name]

    def need(x):
        neg = "!" if x.startswith("!") else ""
        k, _, v = x.lstrip("!").partition(":")
        if k == "rep":
            name, _, n = v.partition(":")
            return "%srep:%s:%d" % (neg, who(name), int(n))
        return x

    def act(a):
        k, _, v = a.partition(":")
        if k == "rep":
            name, _, n = v.partition(":")
            return "rep:%s:%d" % (who(name), int(n))
        return a

    quests = {}
    for name in C["lines"]:
        q = _read(os.path.join(writing, name + ".json"))
        qid = q["id"]
        out = dict(title=q["title"], summary=q["summary"], line=q["group"], rank=q.get("rank", ""), giver=who(q["giver"]),
                   need=[need(x) for x in q.get("needs", [])], start=q["start"], stages={}, endings={})
        for s in q["stages"]:
            key = "%s.%s" % (qid, s["id"])
            st = dict(log=s["goal"])
            if s["kind"] == "talk":
                st["goal"] = dict(talk=who(s["with"]))
            elif key in C["places"]:
                st["goal"] = dict(C["places"][key])
            else:
                raise ValueError("story_cast.json has no place for %s" % key)
            if "nodes" in s:
                st["start"] = s["start"]
                if s.get("starts"):
                    st["starts"] = [dict(need=[need(x) for x in a["need"]], node=a["node"]) for a in s["starts"]]
                st["nodes"] = {}
                talker = st["goal"].get("talk")
                for nid, n in s["nodes"].items():
                    nd = dict(say=n["say"])
                    if n["who"] == "scene":
                        nd["who"] = "scene"
                    else:
                        if who(n["who"]) != talker:
                            nd["who"] = who(n["who"])
                        nd["mood"] = n["mood"]
                    if n.get("dir"):
                        nd["dir"] = n["dir"]
                    if "%s.%s" % (key, nid) in C.get("covered", {}):
                        nd["covered"] = C["covered"]["%s.%s" % (key, nid)]
                    nd["options"] = []
                    for o in n["options"]:
                        op = dict(text=o["text"], next=o["next"])
                        if o.get("need"):
                            op["need"] = [need(x) for x in o["need"]]
                        if o.get("act"):
                            op["act"] = [act(a) for a in o["act"]]
                        nd["options"].append(op)
                    st["nodes"][nid] = nd
            else:
                st["then"] = s["then"]
            out["stages"][s["id"]] = st
        for e in q["endings"]:
            en = dict(title=e["title"], log=e["log"], pay=e.get("pay", 0))
            if e.get("charge"):
                en["charge"] = e["charge"]
            en["rep"] = {who(k): v for k, v in e.get("rep", {}).items()}
            for k in ("give", "take", "flags"):
                if e.get(k):
                    en[k] = list(e[k])
            if e.get("retake"):
                en["retake"] = True
            out["endings"][e["id"]] = en
        quests[qid] = out
    return dict(note=NOTE, exclusive=world.get("exclusive", []), quests=quests)


def text(doc):
    return json.dumps(doc, ensure_ascii=False, indent=1) + "\n"


def up_to_date():
    try:
        with open(OUT, encoding="utf-8") as f:
            return f.read() == text(compile())
    except FileNotFoundError:
        return False


def join(rules, story):
    """World/rules/quests.json with the story lines added: one set of quests for quests.py."""
    out = dict(rules)
    clash = set(rules["quests"]) & set(story["quests"])
    if clash:
        raise ValueError("quest ids used twice: %s" % sorted(clash))
    out["quests"] = dict(rules["quests"], **story["quests"])
    out["exclusive"] = list(rules.get("exclusive", [])) + list(story.get("exclusive", []))
    return out


if __name__ == "__main__":
    if "--check" in sys.argv:
        ok = up_to_date()
        print("quests_story.json is up to date" if ok else "quests_story.json is NOT what the writing gives: run python story.py")
        sys.exit(0 if ok else 1)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text(compile()))
    n = compile()["quests"]
    print("wrote %s: %d quest lines, %d lines said" % (os.path.relpath(OUT, ROOT), len(n), sum(len(s.get("nodes", {})) for q in n.values() for s in q["stages"].values())))
