# Checks the owner's picks and rewrites docs/backlog/BACKLOG.md from features.json and feature_choices.json.
# The owner states picks in chat; an agent writes them into feature_choices.json, then runs this (ADR-0008).
#   powershell -NoProfile -ExecutionPolicy Bypass -File Tools/backlog.ps1
# Exit code 1 if a pick is invalid (unknown feature, level out of range, or a feature that shrinks at a later milestone).
# Unmet needs are warnings: they are allowed, but the level is not in scope until its needs are picked too.
param([string]$Root = (Join-Path $PSScriptRoot ".."))
$ErrorActionPreference = "Stop"
$Root = [IO.Path]::GetFullPath($Root)
$utf8 = New-Object System.Text.UTF8Encoding($false)
function Read-JsonFile($p) { [IO.File]::ReadAllText((Join-Path $Root $p), $utf8) | ConvertFrom-Json }

$data = Read-JsonFile "docs/backlog/features.json"
$file = Read-JsonFile "docs/backlog/feature_choices.json"
$ms = @($data.milestones)
$points = $data.effort.points
$star = [string][char]0x2605
$errors = New-Object System.Collections.ArrayList
$warnings = New-Object System.Collections.ArrayList

$byId = @{}; foreach ($f in $data.features) { $byId[$f.id] = $f }
$choices = @{}
if ($file.choices) {
  foreach ($p in $file.choices.PSObject.Properties) {
    if (-not $byId.ContainsKey($p.Name)) { [void]$errors.Add("unknown feature $($p.Name)"); continue }
    $choices[$p.Name] = $p.Value
  }
}

function Get-Pick($fid, $m) {         # the owner's pick, or $null while undecided
  $c = $choices[$fid]; if ($null -eq $c) { return $null }
  $v = $c.PSObject.Properties[$m]; if ($null -eq $v -or $null -eq $v.Value) { return $null }
  return [int]$v.Value
}
function Get-Effective($fid, $m) {    # the pick, or the suggestion while undecided
  $v = Get-Pick $fid $m; if ($null -ne $v) { return $v }
  return [int]$byId[$fid].suggested.$m
}
function Get-Cost($f, $level) {       # points to reach a level from nothing
  if ($level -lt 0) { return 0 }
  $n = 0; for ($i = 0; $i -le $level; $i++) { $n += [int]$points.($f.levels[$i].effort) }; return $n
}
function Get-LevelName($f, $lv) { if ($null -eq $lv) { "undecided" } elseif ($lv -lt 0) { "Out" } else { "$lv $($f.levels[$lv].name)" } }

# validate
foreach ($fid in $choices.Keys) {
  $f = $byId[$fid]; $prev = $null; $prevName = $null
  foreach ($m in $ms) {
    $v = Get-Pick $fid $m.id
    if ($null -eq $v) { continue }
    if ($v -lt -1 -or $v -ge $f.levels.Count) { [void]$errors.Add("$fid at $($m.name): level $v does not exist"); continue }
    if ($null -ne $prev -and $v -lt $prev) { [void]$errors.Add("$fid shrinks from $prev at $prevName to $v at $($m.name)") }
    $prev = $v; $prevName = $m.name
  }
}
foreach ($f in $data.features) {
  foreach ($m in $ms) {
    $lvl = Get-Effective $f.id $m.id
    if ($null -eq (Get-Pick $f.id $m.id)) { continue }   # only warn about real picks
    for ($i = 0; $i -le $lvl; $i++) {
      $needs = $f.levels[$i].needs
      if ($null -eq $needs) { continue }
      foreach ($n in $needs.PSObject.Properties) {
        $have = Get-Pick $n.Name $m.id        # a need counts only when it is picked (FEATURE_PROCESS rule 2)
        if ($null -eq $have) { [void]$warnings.Add("$($f.id) at $($m.name) needs $($n.Name) at level $($n.Value) (undecided)") }
        elseif ($have -lt [int]$n.Value) { [void]$warnings.Add("$($f.id) at $($m.name) needs $($n.Name) at level $($n.Value) (picked $have)") }
      }
    }
  }
}
if ($errors.Count) { $errors | ForEach-Object { Write-Host "ERROR: $_" }; exit 1 }

# write BACKLOG.md
$L = New-Object System.Collections.Generic.List[string]
$decided = @{}; $mine = @{}; $sug = @{}
foreach ($m in $ms) {
  $decided[$m.id] = 0; $mine[$m.id] = 0; $sug[$m.id] = 0
  foreach ($f in $data.features) {
    $sug[$m.id] += Get-Cost $f ([int]$f.suggested.($m.id))
    $mine[$m.id] += Get-Cost $f (Get-Effective $f.id $m.id)
    if ($null -ne (Get-Pick $f.id $m.id)) { $decided[$m.id]++ }
  }
}
$count = @($data.features).Count
$L.Add("# Feature backlog and the owner's picks"); $L.Add("")
$L.Add("> Generated by ``Tools/backlog.ps1`` from ``features.json`` and ``feature_choices.json``. Do not edit by hand.")
$L.Add("> The owner states picks in chat; agents record them (ADR-0008). A star marks a pick that differs from the suggestion."); $L.Add("")
$L.Add("| | " + (($ms | ForEach-Object { "$($_.name) ($($_.phase))" }) -join " | ") + " |")
$L.Add("|---|" + (($ms | ForEach-Object { "---" }) -join "|") + "|")
$L.Add("| Decided | " + (($ms | ForEach-Object { "$($decided[$_.id]) of $count" }) -join " | ") + " |")
$L.Add("| Size of the plan (points) | " + (($ms | ForEach-Object { $mine[$_.id] }) -join " | ") + " |")
$L.Add("| Size of the suggested plan | " + (($ms | ForEach-Object { $sug[$_.id] }) -join " | ") + " |"); $L.Add("")
if ($warnings.Count) {
  $L.Add("**Needs not met yet** (these levels are not in scope until their needs are picked):"); $L.Add("")
  $warnings | ForEach-Object { $L.Add("- $_") }; $L.Add("")
}
foreach ($a in $data.areas) {
  $L.Add("## $($a.name)"); $L.Add("")
  $L.Add("| Feature | " + (($ms | ForEach-Object { $_.name }) -join " | ") + " | Note |")
  $L.Add("|---|" + (($ms | ForEach-Object { "---" }) -join "|") + "|---|")
  foreach ($f in @($data.features | Where-Object { $_.area -eq $a.id })) {
    $cells = foreach ($m in $ms) {
      $v = Get-Pick $f.id $m.id
      (Get-LevelName $f $v) + $(if ($null -ne $v -and $v -ne [int]$f.suggested.($m.id)) { " $star" } else { "" })
    }
    $note = ""; if ($choices[$f.id] -and $choices[$f.id].note) { $note = ([string]$choices[$f.id].note) -replace '\|', '/' }
    $L.Add("| **$($f.title)** ``$($f.id)`` | " + ($cells -join " | ") + " | $note |")
  }
  $L.Add("")
}
$L.Add("## What each level means"); $L.Add("")
foreach ($f in $data.features) {
  $L.Add("**$($f.title)** (``$($f.id)``). $($f.why)")
  for ($i = 0; $i -lt $f.levels.Count; $i++) { $lv = $f.levels[$i]; $L.Add("- $i $($lv.name): $($lv.what) Size $($lv.effort).") }
  $L.Add("")
}
[IO.File]::WriteAllText((Join-Path $Root "docs/backlog/BACKLOG.md"), ($L -join "`n"), $utf8)
$warnings | ForEach-Object { Write-Host "warning: $_" }
Write-Host ("BACKLOG.md written. Decided: " + (($ms | ForEach-Object { "$($_.name) $($decided[$_.id])/$count" }) -join ", "))
